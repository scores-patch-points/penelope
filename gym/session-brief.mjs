#!/usr/bin/env node
// gym/session-brief.mjs — NOTHING EVERY SESSION MUST MEET, until this (GL-SB-01).
// The regression loop was not forgetting: a session that starts anywhere but inside the right checkout loads none of the project's rules (khora's
// CLAUDE.md had reached no session), memory is keyed by cwd, and three documents gave three answers to "which door". This generates ONE short brief
// from two sources of truth that already exist: the standing rules (gym/session-brief.rules.json) and the capability ledger (experiments/zero-overlap/LEDGER.md).
// Nothing is typed twice, so it cannot rot: gym/session-brief.test.mjs fails when BRIEF.md differs from what this would generate.
// Delivery (a SessionStart hook that prints BRIEF.md) is the owner's decision and is not made here.
//   node gym/session-brief.mjs            print the brief
//   node gym/session-brief.mjs --write    write BRIEF.md at the repo root
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseLedger } from "./ledger-check.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const REFUSED = /(REFUSED|NEGATIVE|FAILED|failed|forged|not independent|not adversarial|launders|collapsed|opposite|uninformative|not enough)/i;
const clip = (s, n) => { const t = String(s).replace(/\s+/g, " ").trim(); return t.length <= n ? t : t.slice(0, n - 1).replace(/[ ,;:(]+\S*$/, "") + "…"; };

/** brief({ rules, rows }) -> the brief text (pure). */
export function brief({ rules = [], rows = [] } = {}) {
  const L = [];
  L.push("# SESSION BRIEF: read this before you work on the Fold/EO research");
  L.push("Generated by `node gym/session-brief.mjs --write` from `gym/session-brief.rules.json` and `experiments/zero-overlap/LEDGER.md`. Do not edit by hand.");
  L.push("");
  L.push("## Before you do anything");
  L.push("- `git fetch` and work from `origin/main` (name the commit you read). Then know the state in three commands: `npm test` · `node gym/ledger-check.mjs` · `node gym/house-ratchet.mjs --list`.");
  L.push("");
  L.push("## Standing rules");
  rules.forEach((r, i) => L.push(`${i + 1}. ${r.rule} (${r.source})`));
  L.push("");
  L.push(`## What is established (${rows.length} ledger rows; label · claim → result)`);
  for (const r of rows) L.push(`- #${r.n} [${r.label}] ${clip(r.claim, 70)} → ${clip(r.result, 150)}`);
  const refused = rows.filter((r) => REFUSED.test(`${r.claim} ${r.result}`));
  L.push("");
  L.push("## Tried and refused (do not redo without a new idea)");
  if (!refused.length) L.push("- (none recorded)");
  for (const r of refused) L.push(`- #${r.n} ${clip(r.claim, 70)}`);
  L.push("");
  L.push("## Where things live");
  L.push("- `experiments/zero-overlap/`: LEDGER.md (claims), splits.json (data splits), measures.jsonl (pinned measures), PREREG*/RESULT* per frame, PLAN-v3.md (order of work).");
  L.push("- `organs/frame-verdicts.mjs`, `relation-fold.mjs`, `vantage-verdicts.mjs`: the judging organs. `GLAUCA-EOT.md`: the laws, with evidence and a falsifying control. `TAPESTRY.md`: the threads.");
  return L.join("\n") + "\n";
}

export function load(root = ROOT) {
  const rules = JSON.parse(fs.readFileSync(path.join(root, "gym", "session-brief.rules.json"), "utf8")).rules;
  const rows = parseLedger(fs.readFileSync(path.join(root, "experiments", "zero-overlap", "LEDGER.md"), "utf8")).filter((r) => !r.malformed);
  return { rules, rows };
}
export const generate = (root = ROOT) => brief(load(root));

if (import.meta.url === `file://${process.argv[1]}` || (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href)) {
  const text = generate();
  if (process.argv.includes("--write")) { fs.writeFileSync(path.join(ROOT, "BRIEF.md"), text); console.log(`session-brief: wrote BRIEF.md (${text.split("\n").length - 1} lines)`); }
  else process.stdout.write(text);
}
